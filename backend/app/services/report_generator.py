class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and render total page count and footer.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))
        # Footer text
        footer_text = f"ResuLyzer ATS Audit Report  |  Confidential  |  Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 36, 25, footer_text)
        self.drawString(36, 25, "Generated by ResuLyzer Platform")
        # Footer dividing line
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, 38, letter[0] - 36, 38)
        self.restoreState()


class ReportGenerator:
    """
    Generates high-quality, professional PDF reports for resume ATS analyses using ReportLab.
    """

    @classmethod
    def generate_pdf(
        cls,
        analysis_data: Dict[str, Any],
        output_filename: str
    ) -> Path:
        output_path = settings.REPORTS_DIR / output_filename

        doc = SimpleDocTemplate(
            str(output_path),
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=40,
            bottomMargin=50
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        brand_title = ParagraphStyle(
            "BrandTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#1E3A8A")
        )

        brand_tagline = ParagraphStyle(
            "BrandTagline",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#475569")
        )

        section_heading = ParagraphStyle(
            "SectionHeading",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#0F172A"),
            spaceBefore=12,
            spaceAfter=6
        )

        body_style = ParagraphStyle(
            "BodyDark",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155")
        )

        bold_label = ParagraphStyle(
            "BoldLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#1E293B")
        )

        story = []

        # 1. Header Banner
        header_table = Table([
            [
                Paragraph("<b>ResuLyzer</b>", brand_title),
                Paragraph(f"<b>Audit Date:</b> {datetime.utcnow().strftime('%B %d, %Y')}<br/><b>Status:</b> Complete", body_style)
            ],
            [
                Paragraph("Understand Your Resume. Improve Your Opportunities.", brand_tagline),
                Paragraph("<b>Platform:</b> ResuLyzer ATS Engine v1.0", body_style)
            ]
        ], colWidths=[360, 180])
        header_table.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
            ('TOPPADDING', (0, 0), (-1, -1), 2),
        ]))
        story.append(header_table)
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceAfter=14))

        # 2. Score Summary Box
        ats_score = analysis_data.get("ats_score", 0.0)
        category = analysis_data.get("category", "Analysis Complete")
        job_title = analysis_data.get("job_title", "Target Position")
        company_name = analysis_data.get("company_name", "N/A")
        resume_filename = analysis_data.get("resume_filename", "Uploaded Resume")

        score_bg = colors.HexColor("#ECFDF5") if ats_score >= 80 else (colors.HexColor("#EFF6FF") if ats_score >= 65 else colors.HexColor("#FFFBEB"))
        score_border = colors.HexColor("#10B981") if ats_score >= 80 else (colors.HexColor("#3B82F6") if ats_score >= 65 else colors.HexColor("#F59E0B"))

        score_box_data = [
            [
                Paragraph(
                    f"<font size=28 color='{score_border.hexval()}'><b>{ats_score:.1f} / 100</b></font><br/>"
                    f"<b>{category}</b>",
                    ParagraphStyle("ScoreDisplay", parent=styles["Normal"], alignment=1, leading=26)
                ),
                Paragraph(
                    f"<b>Job Title:</b> {job_title}<br/>"
                    f"<b>Company:</b> {company_name}<br/>"
                    f"<b>Evaluated Resume:</b> {resume_filename}<br/>"
                    f"<b>Semantic Similarity:</b> {analysis_data.get('semantic_similarity', 0.0):.1f}%",
                    body_style
                )
            ]
        ]
        score_table = Table(score_box_data, colWidths=[200, 340])
        score_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), score_bg),
            ('BOX', (0, 0), (-1, -1), 1.5, score_border),
            ('ALIGN', (0, 0), (0, 0), 'CENTER'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('PADDING', (0, 0), (-1, -1), 10),
        ]))
        story.append(score_table)
        story.append(Spacer(1, 14))

        # 3. Component Score Breakdown Table
        story.append(Paragraph("Component Score Breakdown", section_heading))
        breakdown = analysis_data.get("score_breakdown", {})

        breakdown_rows = [
            [
                Paragraph("<b>Component</b>", bold_label),
                Paragraph("<b>Weight</b>", bold_label),
                Paragraph("<b>Raw Score</b>", bold_label),
                Paragraph("<b>Contribution</b>", bold_label)
            ]
        ]

        for key, comp in breakdown.items():
            label = comp.get("label", key)
            weight = f"{comp.get('weight', 0)}%"
            raw = f"{comp.get('score', 0):.1f} / 100"
            contrib = f"{comp.get('weighted_contribution', 0):.1f} pts"
            breakdown_rows.append([
                Paragraph(label, body_style),
                Paragraph(weight, body_style),
                Paragraph(raw, body_style),
                Paragraph(contrib, body_style)
            ])

        bd_table = Table(breakdown_rows, colWidths=[240, 90, 105, 105])
        bd_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
            ('LINEBELOW', (0, 0), (-1, 0), 1, colors.HexColor("#94A3B8")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        story.append(bd_table)
        story.append(Spacer(1, 14))

        # 4. Matched Skills & Missing Skills
        story.append(Paragraph("Skill Alignment Analysis", section_heading))
        matched = analysis_data.get("matched_skills", [])
        matched_str = ", ".join([m["skill"].title() for m in matched[:15]]) if matched else "None explicitly detected"

        missing = analysis_data.get("missing_skills", {})
        missing_req = missing.get("required", [])
        missing_pref = missing.get("preferred", [])

        req_str = ", ".join([s.title() for s in missing_req[:12]]) if missing_req else "All required skills matched!"
        pref_str = ", ".join([s.title() for s in missing_pref[:10]]) if missing_pref else "None"

        skill_analysis_data = [
            [Paragraph("<b>Matched Skills:</b>", bold_label), Paragraph(matched_str, body_style)],
            [Paragraph("<b>Missing Required Skills:</b>", bold_label), Paragraph(f"<font color='#DC2626'>{req_str}</font>", body_style)],
            [Paragraph("<b>Missing Preferred Skills:</b>", bold_label), Paragraph(pref_str, body_style)]
        ]

        skill_table = Table(skill_analysis_data, colWidths=[160, 380])
        skill_table.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('LINEBELOW', (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
        ]))
        story.append(skill_table)
        story.append(Spacer(1, 14))

        # 5. Experience & Education Overview
        story.append(Paragraph("Experience & Education Comparison", section_heading))
        exp = analysis_data.get("experience_analysis", {})
        edu = analysis_data.get("education_analysis", {})

        exp_edu_data = [
            [
                Paragraph("<b>Work Experience:</b>", bold_label),
                Paragraph(f"{exp.get('status', 'N/A')} &mdash; {exp.get('explanation', '')}", body_style)
            ],
            [
                Paragraph("<b>Education Qualification:</b>", bold_label),
                Paragraph(f"{edu.get('status', 'N/A')} &mdash; {edu.get('explanation', '')}", body_style)
            ]
        ]
        exp_edu_table = Table(exp_edu_data, colWidths=[160, 380])
        exp_edu_table.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('LINEBELOW', (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
        ]))
        story.append(exp_edu_table)
        story.append(Spacer(1, 14))

        # 6. Actionable Recommendations
        recs = analysis_data.get("recommendations", [])
        if recs:
            story.append(KeepTogether([
                Paragraph("Actionable Recommendations for Improvement", section_heading),
                Spacer(1, 4)
            ]))
            for r in recs[:5]:
                priority = r.get("priority", "medium").upper()
                p_color = "#DC2626" if priority == "HIGH" else ("#2563EB" if priority == "MEDIUM" else "#16A34A")
                title = r.get("title", "")
                desc = r.get("description", "")
                action = r.get("action", "")

                rec_cell = [
                    [
                        Paragraph(f"<font color='{p_color}'><b>[{priority}]</b></font> <b>{title}</b>", bold_label),
                    ],
                    [
                        Paragraph(desc, body_style),
                    ],
                    [
                        Paragraph(f"<b>Recommended Action:</b> <i>{action}</i>", body_style)
                    ]
                ]
                rec_t = Table(rec_cell, colWidths=[540])
                rec_t.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                    ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                    ('PADDING', (0, 0), (-1, -1), 6),
                    ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ]))
                story.append(rec_t)
                story.append(Spacer(1, 6))

        # 7. Disclaimer
        story.append(Spacer(1, 10))
        story.append(Paragraph(
            "<b>Disclaimer:</b> ResuLyzer provides analytical estimates based on parsing algorithms and heuristic scoring models. "
            "It does not guarantee interview shortlisting or hiring outcomes. Employers use diverse ATS configurations.",
            ParagraphStyle("Disclaimer", parent=styles["Normal"], fontName="Helvetica-Oblique", fontSize=8, leading=11, textColor=colors.HexColor("#64748B"))
        ))

        # Build PDF with dynamic footer
        doc.build(story, canvasmaker=NumberedCanvas)
        return output_path

report_generator = ReportGenerator()

